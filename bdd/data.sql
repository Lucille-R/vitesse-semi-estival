CREATE TABLE vendeurs (
    id              SERIAL PRIMARY KEY,
    prenom          VARCHAR(50) NOT NULL,
    numero_vendeur  VARCHAR(10) UNIQUE NOT NULL
);

CREATE TABLE produits (
    id           SERIAL PRIMARY KEY,
    nom          VARCHAR(100) NOT NULL,
    prix         NUMERIC(6,2) NOT NULL CHECK (prix >= 0),
    description  TEXT
);

CREATE TABLE ventes (
    id           SERIAL PRIMARY KEY,
    date         DATE NOT NULL,
    heure        TIME NOT NULL,
    vendeur_id   INTEGER NOT NULL REFERENCES vendeurs(id)
);

CREATE TABLE ventes_lignes (
    id              SERIAL PRIMARY KEY,
    vente_id        INTEGER NOT NULL REFERENCES ventes(id) ON DELETE CASCADE,
    produit_id      INTEGER NOT NULL REFERENCES produits(id),
    quantite        SMALLINT NOT NULL CHECK (quantite > 0)
);

